const I18n = {
  SUPPORTED: ['pt-BR', 'en'],
  DEFAULT: 'pt-BR',
  STORAGE_KEY: 'lpc_lang',
  lang: 'pt-BR',

  /** Traduz uma chave, substituindo {variáveis}. Retorna a própria chave se faltar. */
  t(key, vars = {}) {
    const dict = TRANSLATIONS[this.lang] || TRANSLATIONS[this.DEFAULT];
    let str = dict[key];
    if (str === undefined) str = TRANSLATIONS[this.DEFAULT][key];
    if (str === undefined) return key;
    return str.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : ''));
  },

  locale() { return this.lang === 'en' ? 'en-US' : 'pt-BR'; },

  money(value) {
    return new Intl.NumberFormat(this.locale(), { style: 'currency', currency: 'BRL' }).format(value);
  },

  date(iso, opts = { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }) {
    const d = new Date(iso + 'T12:00:00');
    return new Intl.DateTimeFormat(this.locale(), opts).format(d);
  },

  /** Lê a preferência salva (localStorage se houver consentimento; senão sessionStorage). */
  load() {
    const saved = SafeStorage.get(this.STORAGE_KEY, null) || SafeStorage.get(this.STORAGE_KEY, null, window.sessionStorage);
    this.lang = this.SUPPORTED.includes(saved) ? saved : this.DEFAULT;
    return this.lang;
  },

  save() {
    const canPersist = window.ConsentManager && ConsentManager.canStore('preferences');
    if (canPersist) {
      SafeStorage.set(this.STORAGE_KEY, this.lang);
    } else {
      SafeStorage.remove(this.STORAGE_KEY);
      SafeStorage.set(this.STORAGE_KEY, this.lang, window.sessionStorage);
    }
  },

  /** Aplica traduções em todo o documento (ou em um nó raiz). */
  apply(root = document) {
    document.documentElement.lang = this.lang;
    root.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = this.t(node.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-attr]').forEach((node) => {
      node.dataset.i18nAttr.split(';').forEach((pair) => {
        const [attr, key] = pair.split(':').map((s) => s && s.trim());
        if (attr && key && /^(aria-label|placeholder|alt|title|content)$/.test(attr)) {
          node.setAttribute(attr, this.t(key));
        }
      });
    });
  }
};

/** Função pública exigida pela especificação. */
function applyLanguage(lang) {
  I18n.lang = I18n.SUPPORTED.includes(lang) ? lang : I18n.DEFAULT;
  I18n.save();
  I18n.apply();
  document.dispatchEvent(new CustomEvent('lpc:langchange', { detail: { lang: I18n.lang } }));
}

window.TRANSLATIONS = TRANSLATIONS;
window.I18n = I18n;
window.applyLanguage = applyLanguage;
